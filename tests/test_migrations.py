"""Le migrazioni Alembic devono creare esattamente lo schema dei modelli, e tornare indietro."""

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect

from timbro.db import Database


def cfg_for(db: Database, conn) -> Config:
    from pathlib import Path

    import timbro.db

    cfg = Config()
    cfg.set_main_option("script_location", str(Path(timbro.db.__file__).parent / "migrations"))
    cfg.attributes["connection"] = conn
    return cfg


def test_schema_allineato_ai_modelli(database_url):
    db = Database(database_url)
    db.migrate()
    with db.engine.begin() as conn:
        try:
            command.check(cfg_for(db, conn))
        except AutogenerateDiffsDetected as e:  # modello cambiato senza nuova migrazione
            raise AssertionError(f"serve una nuova migrazione: {e}") from e
    tables = set(inspect(db.engine).get_table_names())
    assert {"users", "devices", "pairing_codes", "punches", "stamps", "alembic_version"} <= tables
    db.dispose()


def test_downgrade_e_upgrade(database_url):
    db = Database(database_url)
    db.migrate()
    with db.engine.begin() as conn:
        command.downgrade(cfg_for(db, conn), "base")
    assert set(inspect(db.engine).get_table_names()) <= {"alembic_version"}
    db.migrate()
    assert "punches" in inspect(db.engine).get_table_names()
    db.dispose()
